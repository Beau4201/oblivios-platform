package org.freeholdos.passwords.hosttest

import org.freeholdos.passwords.keys.BiometricKeyInvalidated

/** Contract tests of KeyGateway against the fake; the real Keystore is checked on a device (PWM-007, PWM-008). */
fun main() {
    missingHardwareSecretIsReportedNotRegenerated()
    hardwareSecretIsStable()
    enrolmentChangeInvalidatesTheBiometricWrapper()
    biometricRoundTrip()
    indexKeyIsStableAcrossCalls()
    callersCannotChangeTheKeys()
    Check.done("KeyGatewayTest")
}

private fun missingHardwareSecretIsReportedNotRegenerated() {
    val g = FakeKeyGateway()
    Check.that("no secret before it was created", g.hardwareSecret() == null && !g.hasHardwareSecret())
    Check.that("asking twice still creates nothing", g.hardwareSecret() == null && g.hardwareSecretsCreated == 0)
    val first = g.createHardwareSecret()
    Check.equal("a secret has 32 bytes", 32, first.size)
    Check.that("a created secret is reported present", g.hasHardwareSecret())
    g.loseHardwareSecret()
    Check.that("a lost secret is reported as missing", g.hardwareSecret() == null && !g.hasHardwareSecret())
    Check.equal("and nothing was regenerated by the lookup", 1, g.hardwareSecretsCreated)
    val second = g.createHardwareSecret()
    Check.that("a new secret is a different secret, made only on request", !first.contentEquals(second))
}

private fun hardwareSecretIsStable() {
    val g = FakeKeyGateway()
    val s = g.createHardwareSecret()
    Check.bytes("the secret is the same on every read", s, g.hardwareSecret()!!)
}

private fun enrolmentChangeInvalidatesTheBiometricWrapper() {
    val g = FakeKeyGateway()
    val vk = ByteArray(32) { it.toByte() }
    val wrapped = g.finishWrap(g.biometricCipherForWrap(), vk)
    Check.that("valid before the change", g.biometricsStillValid())
    g.simulateEnrolmentChange()
    Check.that("invalid after the change", !g.biometricsStillValid())
    Check.throws<BiometricKeyInvalidated>("the old wrapper no longer opens") { g.biometricCipherForUnwrap(wrapped) }
}

private fun biometricRoundTrip() {
    val g = FakeKeyGateway()
    val vk = ByteArray(32) { (it * 7).toByte() }
    val wrapped = g.finishWrap(g.biometricCipherForWrap(), vk)
    Check.that("the wrapper is not the key", !wrapped.contentEquals(vk) && wrapped.size > vk.size)
    Check.bytes("unwrap returns the key", vk, g.finishUnwrap(g.biometricCipherForUnwrap(wrapped), wrapped))
    val other = g.finishWrap(g.biometricCipherForWrap(), vk)
    Check.that("two wraps of the same key differ (fresh IV)", !wrapped.contentEquals(other))
    g.deleteBiometricKey()
    Check.that("a deleted key is not valid", !g.biometricsStillValid())
}

private fun indexKeyIsStableAcrossCalls() {
    val g = FakeKeyGateway()
    val a = g.indexKey()
    Check.equal("32 bytes", 32, a.size)
    Check.bytes("the same on the next call", a, g.indexKey())
    Check.that("independent of the hardware secret", !a.contentEquals(g.createHardwareSecret()))
}

private fun callersCannotChangeTheKeys() {
    val g = FakeKeyGateway()
    val s = g.createHardwareSecret()
    s.fill(0)
    Check.that("wiping the returned array does not wipe the gateway's secret", g.hardwareSecret()!!.any { it != 0.toByte() })
    val k = g.indexKey()
    k.fill(0)
    Check.that("same for the index key", g.indexKey().any { it != 0.toByte() })
}
