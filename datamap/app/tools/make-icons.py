"""Writes the icons of the design reference page as Android vector drawables (ADR-160): the path data is the page's own,
so the app draws the same shapes. A plain symbol becomes a white vector that the app tints; the few symbols with colours
of their own (the filled Apps icon, the shield, the logo of "Your apps") keep them.

usage: make-icons.py DESIGN.html RES_DIR      writes RES_DIR/drawable/ic_<name>.xml
"""
import pathlib
import re
import sys

PLAIN = ["back", "chev", "close", "more", "plus", "minus", "locate", "full", "fullx", "globe", "tune", "lock", "grid",
         "biz", "gear", "info", "pin", "map", "trash", "eye", "hist", "ok", "expand"]
HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- SPDX-License-Identifier: Apache-2.0 -->\n'
          "<!-- Generated by tools/make-icons.py from the design reference page. -->\n")


def fail(message):
    raise SystemExit("make-icons: " + message)


def symbols(src):
    return {m.group(1): (m.group(2), m.group(3))
            for m in re.finditer(r'<symbol id="([^"]+)" viewBox="([^"]+)">(.*?)</symbol>', src, re.S)}


def vector(size, viewport, body):
    return (HEADER + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    android:width="%sdp"\n    android:height="%sdp"\n    android:viewportWidth="%s"\n    android:viewportHeight="%s">\n%s</vector>\n'
            % (size, size, viewport, viewport, body))


def path(d, fill="#FFFFFFFF"):
    return '    <path\n        android:fillColor="%s"\n        android:pathData="%s" />\n' % (fill, d)


def rounded_rect(x, y, w, h, r):
    return ("M%g,%gh%ga%g,%g 0 0 1 %g,%gv%ga%g,%g 0 0 1 %g,%gh%ga%g,%g 0 0 1 %g,%gv%ga%g,%g 0 0 1 %g,%gz"
            % (x + r, y, w - 2 * r, r, r, r, r, h - 2 * r, r, r, -r, r, -(w - 2 * r), r, r, -r, -r, -(h - 2 * r), r, r, r, -r))


def one_path(inner, name):
    d = re.findall(r'<path d="([^"]+)"\s*/?>', inner)
    if len(d) != 1 or "transform" in inner or "fill" in inner:
        fail("symbol %s is not a single plain path" % name)
    return d[0]


def main():
    page, res = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    sym = symbols(page.read_text(encoding="utf-8"))
    out = res / "drawable"
    out.mkdir(parents=True, exist_ok=True)
    for name in PLAIN:
        key = "i-" + name
        if key not in sym:
            fail("no symbol " + key)
        viewbox, inner = sym[key]
        if viewbox != "0 0 24 24":
            fail("%s: viewBox %s" % (key, viewbox))
        (out / ("ic_%s.xml" % name)).write_text(vector(24, 24, path(one_path(inner, key))), encoding="utf-8")
    # the outlined company icon is drawn at 95 percent: the page moves it by scale(.95) translate(.6 .6)
    viewbox, inner = sym["i-bizo"]
    m = re.search(r'<path d="([^"]+)" transform="scale\(\.95\) translate\(\.6 \.6\)"\s*/>', inner)
    if viewbox != "0 0 24 24" or not m:
        fail("i-bizo is not as expected")
    group = ('    <group\n        android:scaleX="0.95"\n        android:scaleY="0.95"\n        android:translateX="0.57"\n'
             '        android:translateY="0.57">\n'
             + "".join("    " + line + "\n" for line in path(m.group(1)).splitlines())
             + "    </group>\n")
    (out / "ic_bizo.xml").write_text(vector(24, 24, group), encoding="utf-8")
    # the filled Apps icon: four rounded squares in the two blues of the page
    viewbox, inner = sym["i-gridf"]
    rects = re.findall(r'<rect x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)" rx="([\d.]+)" fill="(#[0-9A-Fa-f]{6})"/>', inner)
    if viewbox != "0 0 24 24" or len(rects) != 4:
        fail("i-gridf is not as expected")
    body = "".join(path(rounded_rect(float(x), float(y), float(w), float(h), float(r)), "#FF" + f[1:].upper())
                   for x, y, w, h, r, f in rects)
    (out / "ic_gridf.xml").write_text(vector(24, 24, body), encoding="utf-8")
    # the shield: the green of the theme, then a white bolt
    viewbox, inner = sym["i-shield"]
    p = re.findall(r'<path d="([^"]+)" fill="([^"]+)"\s*/>', inner)
    if viewbox != "0 0 24 24" or len(p) != 2 or p[0][1] != "var(--shield)" or p[1][1] != "#fff":
        fail("i-shield is not as expected")
    (out / "ic_shield.xml").write_text(vector(24, 24, path(p[0][0], "@color/at_shield") + path(p[1][0])), encoding="utf-8")
    # the logo of "Your apps": a blue disc with a white globe
    viewbox, inner = sym["logo"]
    stops = re.search(r'<linearGradient id="lg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="(#[0-9A-Fa-f]{6})"/><stop offset="1" stop-color="(#[0-9A-Fa-f]{6})"/>', page.read_text(encoding="utf-8"))
    if not stops:
        fail("no gradient lg")
    disc = ('    <path android:pathData="M18,1a17,17 0 1 0 0,34a17,17 0 1 0 0,-34z">\n        <aapt:attr name="android:fillColor">\n'
            '            <gradient\n                android:type="linear"\n                android:startX="0"\n                android:startY="0"\n'
            '                android:endX="36"\n                android:endY="36">\n'
            '                <item android:offset="0" android:color="#FF%s" />\n                <item android:offset="1" android:color="#FF%s" />\n'
            '            </gradient>\n        </aapt:attr>\n    </path>\n' % (stops.group(1)[1:].upper(), stops.group(2)[1:].upper()))
    stroke = ('    <path\n        android:strokeColor="#FFFFFFFF"\n        android:strokeWidth="1.7"\n        android:strokeLineCap="round"\n'
              '        android:pathData="%s" />\n')
    shapes = ["M18,8a10,10 0 1 0 0,20a10,10 0 1 0 0,-20z",
              "M18,8a4.4,10 0 1 0 0,20a4.4,10 0 1 0 0,-20z",
              "M8,18h20M9.6,12.4h16.8M9.6,23.6h16.8"]
    needed = ['<circle cx="18" cy="18" r="10"/>', '<ellipse cx="18" cy="18" rx="4.4" ry="10"/>', '<path d="M8 18h20M9.6 12.4h16.8M9.6 23.6h16.8"/>']
    if any(n not in inner for n in needed) or 'cx="18" cy="18" r="17"' not in inner:
        fail("the logo is not as expected")
    (out / "ic_logo.xml").write_text(vector(36, 36, disc + "".join(stroke % s for s in shapes)), encoding="utf-8")
    print("wrote %d icons to %s" % (len(PLAIN) + 4, out))


if __name__ == "__main__":
    main()
