"""Writes the colour roles of the design reference page as Android resources, so that the app uses the
page's values and not a copy typed by hand.

usage: extract-tokens.py DESIGN.html RES_DIR
Reads the dark block `.dev,.spec{...}` and the light block `.light .dev,.light .spec{...}` of the page and
writes RES_DIR/values/colors.xml (light) and RES_DIR/values-night/colors.xml (dark).
"""
import pathlib, re, sys

NAMES = ["bg", "row", "hst", "hi", "on", "onv", "ol", "olv", "pri", "onpri", "sec", "onsec", "sc", "osc",
         "err", "inv", "oninv", "icbg", "icfg", "glass"]


def block(css, selector):
    m = re.search(re.escape(selector) + r"\{(.*?)\}", css, re.S)
    if not m:
        raise SystemExit(f"no block {selector}")
    values = dict(re.findall(r"--([a-z0-9]+):\s*([^;]+);", m.group(1)))
    missing = [n for n in NAMES if n not in values]
    if missing:
        raise SystemExit(f"{selector}: missing {missing}")
    return values


def android(value):
    value = value.strip()
    if value.startswith("#"):
        h = value[1:].upper()
        if len(h) == 3:
            h = "".join(c * 2 for c in h)
        if len(h) != 6:
            raise SystemExit(f"colour not understood: {value}")
        return "#FF" + h
    m = re.fullmatch(r"rgba\((\d+),\s*(\d+),\s*(\d+),\s*([0-9.]+)\)", value)
    if not m:
        raise SystemExit(f"colour not understood: {value}")
    r, g, b = (int(m.group(i)) for i in (1, 2, 3))
    a = round(float(m.group(4)) * 255)
    return "#%02X%02X%02X%02X" % (a, r, g, b)


def write(path, values, comment):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- SPDX-License-Identifier: Apache-2.0 -->",
             f"<!-- {comment} Generated by tools/extract-tokens.py from the design reference page. -->", "<resources>"]
    lines += [f'    <color name="dm_{n}">{android(values[n])}</color>' for n in NAMES]
    lines.append("</resources>")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    page, res = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    css = re.search(r"<style[^>]*>(.*?)</style>", page.read_text(encoding="utf-8"), re.S).group(1)
    write(res / "values-night/colors.xml", block(css, ".dev,.spec"), "Dark roles.")
    write(res / "values/colors.xml", block(css, ".light .dev,.light .spec"), "Light roles.")
    print("wrote", res / "values/colors.xml", "and", res / "values-night/colors.xml")


main()
